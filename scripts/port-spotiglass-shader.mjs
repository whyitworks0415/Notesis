// Reproducible GLSL -> Android AGSL adapter. The optical math is upstream code.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assets = path.join(root, 'app/src/main/assets/spotiglass');
const macros = new Map([['GLASS_GRAD_METHOD', '1'], ['SKIA_GRAPHICS_BACKEND', '1']]);
function expand(s) {
  for (let n = 0; n < 8; n++) {
    const next = s.replace(/\b[A-Za-z_]\w*\b/g, w => macros.get(w) ?? w);
    if (next === s) break;
    s = next;
  }
  return s;
}
function condition(s) {
  s = s.replace(/defined\((\w+)\)/g, (_, key) => macros.has(key) ? '1' : '0');
  s = expand(s).replace(/\b[A-Za-z_]\w*\b/g, '0');
  if (!/^[\d\s!&|=().<>+-]+$/.test(s)) throw Error(`Unsupported condition ${s}`);
  return Boolean(Function(`return (${s})`)());
}
function preprocess(file) {
  const lines = fs.readFileSync(path.join(assets, 'upstream', file), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '').split(/\r?\n/);
  const stack = [];
  let active = true;
  const output = [];
  for (const line of lines) {
    const directive = line.trim().match(/^#(\w+)\s*(.*)$/);
    if (!directive) { if (active) output.push(expand(line)); continue; }
    const [, kind, body] = directive;
    if (['if', 'ifdef', 'ifndef'].includes(kind)) {
      const pass = kind === 'ifdef' ? macros.has(body) : kind === 'ifndef' ? !macros.has(body) : condition(body);
      stack.push({ parent: active, seen: pass }); active = active && pass;
    } else if (kind === 'else' || kind === 'elif') {
      const top = stack.at(-1);
      const pass = kind === 'else' || condition(body);
      active = top.parent && !top.seen && pass; top.seen ||= pass;
    } else if (kind === 'endif') { active = stack.pop().parent; }
    else if (active && kind === 'define') {
      const m = body.match(/^(\w+)(\s+.*)?$/);
      if (m) macros.set(m[1], (m[2] ?? '1').trim());
      // PIXEL_TO_NORM is an unused function macro in the upstream entry.
      else if (!body.startsWith('PIXEL_TO_NORM(')) throw Error(`Unsupported macro ${body}`);
    } else if (active && kind === 'include') {
      if (body.includes('common.glsl') || body.includes('border.glsl')) output.push(preprocess(body.slice(1, -1)));
      // Flutter entry/gradient headers are replaced by the analytic Skia path.
    }
  }
  if (stack.length) throw Error('Unbalanced preprocessor');
  return output.join('\n');
}
let shader = preprocess('liquid_glass.frag')
  .replace(/^\s*precision[^;]+;/gm, '')
  .replace(/\bvec([234])\b/g, 'float$1').replace(/\bmat([234])\b/g, 'float$1x$1')
  .replace('uniform sampler2D u_texture_input;', 'uniform shader u_texture_input;')
  .replace('out float4 frag_color;', '')
  .replace(/texture\(u_texture_input, ([^)]+)\)/g, 'sampleBackdrop($1)')
  .replace('void main() {', 'float4 renderLens(float2 fragCoord) {')
  .replace('FlutterFragCoord().xy', 'fragCoord')
  .replace(/frag_color = (.*);\s*return;/g, 'return $1;')
  .replace(/frag_color = (.*);/g, 'return $1;')
  .replace(/any\(notEqual\(u_xformRow, float4\(1.0, 0.0, 0.0, 1.0\)\)\)/g, '(u_xformRow != float4(1.0, 0.0, 0.0, 1.0))')
  .replace(/any\(notEqual\(u_xformOff, float2\(0.0\)\)\)/g, '(u_xformOff != float2(0.0))');
// AGSL child shaders use pixel coordinates; GLSL texture() uses normalized UVs.
shader = shader.replace('uniform shader u_texture_input;', `uniform shader u_texture_input;
float4 sampleBackdrop(float2 uv) {
    float4 c = u_texture_input.eval(uv * u_resolution);
    return float4(c.rgb / max(c.a, 0.0001), c.a);
}`);
// The source lens draws into an overlay. RenderEffect draws the entire captured
// capsule instead: preserve its source pixels outside the lens and interpolate
// the coverage at the edge (without painting the icons twice through the lens).
shader += `
half4 main(float2 p) {
    float4 original = u_texture_input.eval(p);
    // Flutter only shades the lens bounds. RenderEffect covers the whole
    // capsule: cull outside the same bounds before evaluating its optics.
    float2 halfSize = u_lensGeom.xy * 0.5;
    float2 center = u_touch + halfSize;
    float aa = max(u_shapeAaPx, 1.0);
    if (abs(p.x - center.x) > halfSize.x + aa ||
        abs(p.y - center.y) > halfSize.y + aa) return half4(original);
    float4 lens = renderLens(p);
    return half4(lens.rgb + original.rgb * (1.0 - lens.a),
                 lens.a + original.a * (1.0 - lens.a));
}
`;
const header = '// Generated by scripts/port-spotiglass-shader.mjs; do not edit.\n' +
  '// Port of liquid_glass_easy 4.3.2. Copyright (c) 2025 Ahmed Gamil. MIT.\n' +
  '// See spotiglass/upstream/liquid_glass_easy.LICENSE.\n';
fs.writeFileSync(path.join(assets, 'liquid_glass.agsl'), header + shader.replace(/[ \t]+$/gm, '').replace(/\n\s*\n+/g, '\n'));
console.log('Generated Spotiglass AGSL from upstream GLSL.');
